#include<iostream>
using namespace std;
int main()
{
    int num1=12; // variable declaration 
    int num2=3;
    
    // num1 = 12 and num2 = 3 
    cout<<"num1 = "<<num1<<" and num2 = "<<num2<<endl;
    
    int sum;
    sum = num1 + num2;
    // 12 + 3 = 15 
    cout<<num1<<" + "<<num2<<" = "<<sum;
    return 0;
}